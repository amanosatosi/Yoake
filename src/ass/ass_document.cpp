QStringList splitEventFields(QStringView value)
{
    QStringList fields;
    qsizetype start = 0;
    for (int field = 0; field < 9; ++field) {
        const auto comma = value.indexOf(u',', start);
        if (comma < 0)
            return {};
        fields.push_back(value.mid(start, comma - start).toString().trimmed());
        start = comma + 1;
    }
    fields.push_back(value.mid(start).toString());
    return fields;
}

bool parseInteger(QStringView value, int *result)
{
    bool ok = false;
    const int parsed = value.trimmed().toInt(&ok);
    if (ok)
        *result = parsed;
    return ok;
}

bool parseEventLine(const QString &line, Event *event)
{
    const bool dialogue = line.startsWith(QStringLiteral("Dialogue:"), Qt::CaseInsensitive);
    const bool comment = line.startsWith(QStringLiteral("Comment:"), Qt::CaseInsensitive);
    if (!dialogue && !comment)
        return false;

    const auto colon = line.indexOf(u':');
    const auto fields = splitEventFields(QStringView(line).mid(colon + 1));
    if (fields.size() != 10)
        return false;

    bool startOk = false;
    bool endOk = false;
    Event parsed;
    parsed.comment = comment;
    if (!parseInteger(fields[0], &parsed.layer))
        return false;
    parsed.startMs = parseTime(fields[1], &startOk);
    parsed.endMs = parseTime(fields[2], &endOk);
    parsed.style = fields[3].isEmpty() ? QStringLiteral("Default") : fields[3];
    parsed.actor = fields[4];
    if (!parseInteger(fields[5], &parsed.marginLeft)
        || !parseInteger(fields[6], &parsed.marginRight)
        || !parseInteger(fields[7], &parsed.marginVertical)) {
        return false;
    }
    parsed.effect = fields[8];
    parsed.text = fields[9];
    if (!startOk || !endOk || parsed.endMs < parsed.startMs)
        return false;
    *event = std::move(parsed);
    return true;
}

QString serializeEvent(const Event &event)
{
    const QStringList fields = {
        QString::number(event.layer),
        formatTime(event.startMs),
        formatTime(event.endMs),
        event.style,
        event.actor,
        QStringLiteral("%1").arg(event.marginLeft, 4, 10, QLatin1Char('0')),
        QStringLiteral("%1").arg(event.marginRight, 4, 10, QLatin1Char('0')),
        QStringLiteral("%1").arg(event.marginVertical, 4, 10, QLatin1Char('0')),
        event.effect,
        event.text
    };
    return (event.comment ? QStringLiteral("Comment: ") : QStringLiteral("Dialogue: "))
        + fields.join(u',');
}

