    private static readonly Dictionary<string,string[]> Readings=KanaReadings.GroupBy(p=>p.Kana,StringComparer.Ordinal).ToDictionary(g=>g.Key,g=>g.Select(p=>p.Romaji).ToArray(),StringComparer.Ordinal);
    private static readonly Dictionary<string,(string Kana,string Romaji)[]> Kana=RomanizedKana.GroupBy(p=>p.Romaji,StringComparer.Ordinal).ToDictionary(g=>g.Key,g=>g.ToArray(),StringComparer.Ordinal);
    public static string[] ForKana(string kana)=>Readings.GetValueOrDefault(kana)??[];
    public static (string Kana,string Romaji)[] ForRomaji(string romaji)
    {
        for(var length=Math.Min(3,romaji.Length);length>0;length--)if(Kana.TryGetValue(romaji[..length],out var matches))return matches;
        return [];
    }
