#!/usr/bin/env python3
"""Generate NativeAOT-safe bindings from the audited exact 3.5 shipped table."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CONTEXTS = {"Always": "Always", "Audio": "Audio", "Default": "Default", "Styling Assistant": "Styling",
    "Subtitle Edit Box": "SubtitleEdit", "Subtitle Grid": "SubtitleGrid", "Translation Assistant": "Translation", "Video": "Video"}


def generate():
    inventory = json.loads((ROOT / "docs/compatibility/aegisub-command-source-inventory.json").read_text(encoding="utf-8"))
    table = inventory["hotkeys"]["3.5.0"]["contexts"]
    if set(table) != set(CONTEXTS):
        raise ValueError("Unexpected upstream context; review it rather than flattening contexts")
    lines = ["// Generated by tools/generate_aegisub_hotkeys.py; do not hand-edit.",
        "// Aegisub v3.5.0, commit 43af875ea01e80052cc6c44f24fc8c5258261c6d.",
        "// Source: src/libresrc/default_hotkey.json. Exact provenance and hashes:",
        "// docs/compatibility/aegisub-command-source-inventory.json.",
        "namespace Yoake.Core.Hotkeys;", "", "public static partial class AegisubHotkeyDefaults", "{",
        "    public static IReadOnlyList<HotkeyBinding> ReferenceBindings { get; } = Array.AsReadOnly<HotkeyBinding>(", "    ["]
    for context, commands in table.items():
        for command, gestures in commands.items():
            for gesture in gestures:
                lines.append(f"        new({json.dumps(command)}, HotkeyContext.{CONTEXTS[context]}, HotkeyGesture.Parse({json.dumps(gesture)})),")
    lines.extend(["    ]);", "}", ""])
    return "\n".join(lines)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    path = ROOT / "src/Yoake.Core/Hotkeys/AegisubHotkeyDefaults.g.cs"
    content = generate()
    if args.check:
        if not path.exists() or path.read_text(encoding="utf-8") != content:
            raise SystemExit("Aegisub hotkey bindings are stale; run python tools/generate_aegisub_hotkeys.py")
    else:
        path.write_text(content, encoding="utf-8")
    print("aegisub-hotkey-defaults: OK")
